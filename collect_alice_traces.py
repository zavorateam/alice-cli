async def collect_turns(manager, agent_id, dialog_id, prompt, timeout):
    turns = []
    async def _consume():
        async for turn in manager.send_message(prompt, agent_id=agent_id, dialog_id=dialog_id):
            try:
                turns.append(turn.to_dict())
            except Exception:
                turns.append({"text": getattr(turn, "text", ""), "error": getattr(turn, "error", None), "is_finished": getattr(turn, "is_finished", False)})
    await asyncio.wait_for(_consume(), timeout=timeout)
