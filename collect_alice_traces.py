def select_hf_config_servers(config):
    selected = []
    for name, spec in (config.get("mcpServers") or {}).items():
        values = " ".join([str(name), str(spec.get("command", "")), " ".join(map(str, spec.get("args", [])))])
        if re.search(r"hugging\s*face|huggingface|(^|[\\/_-])hf([\\/_-]|$)", values, re.I):
            selected.append((name, spec))
    return selected


def is_readonly_hf_tool(server_name, tool):
    desc = str(getattr(tool, "description", ""))
    name = str(getattr(tool, "name", ""))
    hay = (server_name + " " + name + " " + desc).lower()
    if re.search(r"delete|remove|create|upload|publish|deploy|train|execute|write|update|edit|commit|purchase|inference|predict|run\s+model", hay):
        return False
    return bool(re.search(r"hugging\s*face|huggingface|\bhf\b|model|dataset|space|search|list|read|find|inspect|card|metadata", hay)) and bool(re.search(r"search|list|get|read|find|inspect|card|metadata|info", name.lower() + " " + desc.lower()))


async def load_readonly_hf_tools():
    if not DO_HF_TOOLS:
        return None, "disabled by flag"
    if not CONFIG_PATH.is_file():
        return None, "tool config not found"
    try:
        config = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
    except Exception as exc:
        return None, "tool config parse failed: " + type(exc).__name__
    servers = select_hf_config_servers(config)
    if not servers:
        return None, "no Hugging Face MCP server configured"
    try:
        from local_tools import LocalToolRegistry
    except Exception as exc:
        return None, "local_tools import failed: " + type(exc).__name__
    source = LocalToolRegistry()
    for name, spec in servers:
        try:
            command = [str(spec["command"])] + list(spec.get("args", []))
            await source.add_mcp_server(name, command, spec.get("env"))
        except Exception as exc:
            write_jsonl("hf_tool_results.jsonl", {"kind": "hf_mcp_start_error", "server": name, "error_type": type(exc).__name__, "error": str(exc)})
    if not source.tools:
        await source.close()
        return None, "HF MCP servers exposed no tools"
    filtered = LocalToolRegistry()
    allowed = []
    for name, tool in source.tools.items():
        source_server = next((sname for sname, _ in servers if name.startswith(sname + "__") or name.startswith(sname + "_")), servers[0][0])
        if is_readonly_hf_tool(source_server, tool):
            filtered.register(tool)
            allowed.append({"name": name, "description": str(getattr(tool, "description", ""))[:250], "schema": getattr(tool, "arg_schema", {})})
    filtered._clients = source._clients
    if not filtered.tools:
        await filtered.close()
        return None, "HF MCP had no clearly read-only search/metadata tools"
    write_jsonl("hf_tool_results.jsonl", {"kind": "hf_mcp_tools_selected", "tools": allowed})
    return filtered, "selected %d read-only tools" % len(filtered.tools)


