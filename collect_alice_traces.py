def redact_for_archive(value: Any, key: Optional[str] = None) -> Any:
    if key and re.search(r"(^|[_-])(authorization|cookie|cookies|token|secret|password|credential|api_key|apikey|icookie|session_id|sessionid2|spravka|auth|device_uuid|hf_token|hugging_face_hub_token)([_-]|$)", key, re.I):
        if key.lower() not in ("auth_type",):
            return "[REDACTED]"
    if isinstance(value, dict):
        return {k: redact_for_archive(v, str(k)) for k, v in value.items()}
    if isinstance(value, list):
        return [redact_for_archive(v) for v in value]
    if isinstance(value, str):
        s = value
        s = re.sub(r"y0_[A-Za-z0-9._~+/-]{3,}={0,2}", "[REDACTED_OAUTH_TOKEN]", s)
        s = re.sub(r"(?i)\b(Session_id|sessionid2|spravka|icookie|yandexuid|alice_uuid|ya24|_yasc|yp|ys|L|i)\s*(?:=|:)\s*[^;\s,]+", r"\1=[REDACTED]", s)
        if Path.home().as_posix() not in ("", "/"):
            s = s.replace(Path.home().as_posix(), "~")
        return s
    return value


def _run_text(command: List[str], cwd: Path, timeout: int = 8) -> str:
    try:
        p = subprocess.run(command, cwd=str(cwd), stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                           text=True, encoding="utf-8", errors="replace", timeout=timeout, check=False)
        return p.stdout[:200_000]
    except Exception as e:
        return f"unavailable: {type(e).__name__}: {e}"


def build_manifest(root: Path, args: argparse.Namespace, command: List[str], exit_code: int, elapsed: float) -> Dict[str, Any]:
    git_ok = (root / ".git").exists()
    def git(*argv: str) -> str:
        return _run_text(["git", *argv], root).strip() if git_ok else "not a git repository"
    # Avoid pip/importlib.metadata scans here: in some managed Python installs
    # they can be extremely slow or enumerate environment-specific package paths.
    # Record declared dependencies instead; runtime errors and versions remain visible
    # in the logs without allowing manifest collection to stall the whole export.
    deps = {"inventory_status": "declared_requirements_only", "declared_requirements": []}
    req_file = root / "requirements.txt"
    if req_file.is_file():
        try:
            for raw_line in req_file.read_text(encoding="utf-8", errors="replace").splitlines():
                line = raw_line.strip()
                if not line or line.startswith(("#", "-")):
                    continue
                deps["declared_requirements"].append(line[:500])
        except Exception as exc:
            deps["inventory_error"] = type(exc).__name__ + ": " + str(exc)
    safe_command = []
    hide_next = False
    for item in command:
        if hide_next:
            safe_command.append("[REDACTED_ARG]")
            hide_next = False
            continue
        if item in ("--auth", "--token", "--cookies"):
            safe_command.append(item)
            hide_next = True
        elif re.match(r"--(?:auth|token|cookies)=", item):
            safe_command.append(item.split("=", 1)[0] + "=[REDACTED_ARG]")
        elif re.match(r"y0_[A-Za-z0-9._~+/-]{3,}", item):
            safe_command.append("[REDACTED_OAUTH_TOKEN]")
        else:
            safe_command.append(item.replace(str(Path.home()), "~") if str(Path.home()) not in ("", "/") else item)
    env_names = sorted(k for k in os.environ if k.startswith(("ALICE_", "YANDEX_", "PYTHON", "HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY", "NO_PROXY")))
    source_inventory = []
    skip_dirs = {".git", ".venv", "venv", "__pycache__", ".pytest_cache", "trace_exports", "node_modules"}
    tracked = set()
    if git_ok:
        tracked_text = git("ls-files")
        tracked = {x.strip() for x in tracked_text.splitlines() if x.strip()}
    source_suffixes = {".py", ".pyi", ".json", ".toml", ".yaml", ".yml", ".md", ".txt", ".ini", ".cfg", ".sh", ".ps1"}
    secret_names = {"token.txt", ".alice_token", ".alice_cookies", "cookies.txt", ".env", ".alice_device_uuid"}
    for base, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in skip_dirs and d not in {"logs", "data", "downloads", "attachments"}]
        for name in files:
            p = Path(base) / name
            rel = p.relative_to(root).as_posix()
            if any(part in (".git", ".venv", "venv", "__pycache__", "node_modules", "logs", "data", "downloads", "attachments") for part in p.parts): continue
            if name.lower() in secret_names or name.lower().endswith((".cookie", ".cookies", ".pem", ".key")): continue
            if p.suffix.lower() not in source_suffixes: continue
            if tracked and rel not in tracked and p.suffix.lower() not in {".py", ".pyi", ".json", ".toml", ".yaml", ".yml", ".md", ".sh", ".ps1"}: continue
            try:
                st = p.stat()
                if st.st_size > 25 * 1024 * 1024: continue
                h = hashlib.sha256(p.read_bytes()).hexdigest()
                source_inventory.append({"path": rel, "bytes": st.st_size, "sha256": h})
            except Exception: pass
            if len(source_inventory) >= 5000: break
        if len(source_inventory) >= 5000: break
    return {
        "collector_version": VERSION,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "target": args.target,
        "command_redacted": safe_command,
        "exit_code": exit_code,
        "runtime_seconds": elapsed,
        "python": {"version": sys.version, "implementation": platform.python_implementation(), "executable": sys.executable.replace(str(Path.home()), "~") if str(Path.home()) not in ("", "/") else sys.executable},
        "platform": {"system": platform.system(), "release": platform.release(), "machine": platform.machine(), "python_platform": sys.platform},
        "repository": {"path": "<REPOSITORY_ROOT>", "branch": git("branch", "--show-current"), "head": git("rev-parse", "HEAD"), "status": git("status", "--short", "--branch"), "recent_commits": git("log", "-5", "--oneline"), "diff_stat": git("diff", "--stat"), "diff_cached_stat": git("diff", "--cached", "--stat")},
        "environment_variable_names_only": env_names,
        "dependency_inventory": deps,
        "source_inventory": source_inventory,
        "capture": {"http_text_json_bodies": not args.no_http_bodies, "raw_binary_payloads": False, "automatic_upload": False, "secrets_redacted": True},
    }


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Autonomously run Alice CLI diagnostic scenarios and export a redacted trace archive."
    )
    parser.add_argument("--mode", choices=("batch", "interactive"), default="batch",
                        help="batch runs a non-interactive scenario matrix (default); interactive is legacy mode.")
    parser.add_argument("--root", help="Repository root (defaults to the directory containing this script).")
    parser.add_argument("--target", choices=("alice_tools_cli.py", "alice_cli.py", "alice_server.py"), default=DEFAULT_TARGET,
                        help="Application entry point for legacy interactive mode.")
    parser.add_argument("--output-dir", default="trace_exports", help="Where to save the ZIP (default: ./trace_exports).")
    parser.add_argument("--tools-config", default=None, help="Tool configuration path (default: ./alice_tools.json).")
    parser.add_argument("--max-turns", type=int, default=96,
                        help="Maximum number of Alice chat scenarios to run (default: 96).")
    parser.add_argument("--max-agents", type=int, default=0,
                        help="Maximum discovered agents/apps to probe; 0 means all, subject to --max-turns.")
    parser.add_argument("--timeout", type=float, default=90.0,
                        help="Per-scenario timeout in seconds (default: 90).")
    parser.add_argument("--total-timeout", type=float, default=14400.0,
                        help="Hard wall-clock deadline for the complete run in seconds (default: 14400 / 4 hours).")
    parser.add_argument("--no-hf-api", action="store_true", help="Skip the read-only public Hugging Face Hub API probes.")
    parser.add_argument("--no-hf-tools", action="store_true", help="Skip configured read-only Hugging Face MCP tools and Meeseeks traces.")
    parser.add_argument("--no-default-debug-flags", action="store_true", help="Legacy interactive mode only.")
    parser.add_argument("--no-http-bodies", action="store_true", help="Capture HTTP metadata only; do not capture text/JSON bodies.")
    parser.add_argument("app_args", nargs=argparse.REMAINDER, help="Arguments passed to the app in legacy interactive mode; place them after --.")
    args = parser.parse_args()
    if args.max_turns < 1:
        parser.error("--max-turns must be >= 1")
    if args.max_agents < 0:
        parser.error("--max-agents must be >= 0")
    if args.timeout <= 0:
        parser.error("--timeout must be > 0")
    if args.total_timeout <= 0:
        parser.error("--total-timeout must be > 0")
    return args

def main() -> int:
    try:
        return run_capture(parse_args())
    except KeyboardInterrupt:
        print("\nCollector interrupted.", file=sys.stderr)
        return 130


if __name__ == "__main__":
    raise SystemExit(main())
